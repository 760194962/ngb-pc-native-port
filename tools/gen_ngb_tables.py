#!/usr/bin/env python3
"""Generate the NINJA GAIDEN BLACK x2.1 library hook tables (address, size, name) for the loader.

Like gen_section_table.py, but the input is the port project's work/functions_x21.csv (route A's xboxrecomp
function boundaries + XbSymbolDatabase and ngbrecomp names, see docs/02) and one run writes every hooked section.
Output holds addresses, sizes and symbol names only, no game code; valid for the build whose SHA-256 is in
src/build_profile.h (kProfileNgbHurricaneX21).

Usage: python -I tools/gen_ngb_tables.py <functions_x21.csv> loader/src/ngb
"""
import csv
import os
import sys

SECTIONS = {'D3D': 'd3d_functions.inc', 'DSOUND': 'dsound_functions.inc', 'XPP': 'xpp_functions.inc'}
BUILD = 'aa3c5bec...'

if len(sys.argv) != 3:
    sys.exit(__doc__)
src, out_dir = sys.argv[1], sys.argv[2]
os.makedirs(out_dir, exist_ok=True)
rows = list(csv.DictReader(open(src, encoding='utf-8')))
for section, fname in SECTIONS.items():
    sel = [r for r in rows if r['section'] == section]
    sel.sort(key=lambda r: int(r['address'], 16))
    # route A's detector emits overlapping aliases (tail_jump_alias): keep the first function at each address
    seen = set()
    dst = os.path.join(out_dir, fname)
    with open(dst, 'w', newline='\n') as f:
        f.write('// Generated by tools/gen_ngb_tables.py %s from functions_x21.csv. Do not edit.\n' % section)
        f.write('// Functions in the XBE\'s %s section (NINJA GAIDEN BLACK x2.1, SHA-256 %s): address, size in bytes, name.\n' % (section, BUILD))
        n = 0
        for r in sel:
            a = int(r['address'], 16)
            if a in seen:
                continue
            seen.add(a)
            f.write('{0x%08xu, %su, "%s"},\n' % (a, r['size'], r['name']))
            n += 1
    print('wrote %d entries to %s' % (n, dst))
