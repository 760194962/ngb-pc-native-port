"""The Hurricane patches' base image, as layout data for the launcher (launcher/src/ngb_base_layout.inc).

The patches (xdelta, by the translator) apply to one image: "NINJA GAIDEN BLACK.iso", 6,276,317,184 bytes, SHA-1
d35859d1f3a43ce793dbe3e914a5188f4e83ad67. It is extract-xiso 2.7.1's rewrite of the US release's Redump disc (game
partition at 0x18300000): files in the order of a pre-order walk of each directory's tree, each padded with 0xFF to its
sector, the image padded with zeros to a 64 KiB multiple; update.xbe and dashupdate.xbe left out; the certificate of
default.xbe (20 bytes) and of NinjaTomoe.xbe / NinjaTrilogy.xbe (4 bytes each) changed (2026-11-12). So the launcher
makes it from a Redump image with what is here: the first 64 KiB (extract-xiso's banner), the volume header, the four
directory tables (names, sectors, sizes) and those bytes. No game data.

    python -I tools/gen_ngb_base_layout.py "NINJA GAIDEN BLACK.iso" "Ninja Gaiden Black (USA) (En,Ja).iso" launcher/src/ngb_base_layout.inc
"""
import hashlib
import struct
import sys

REDUMP_PART = 0x18300000


def tree(f, part):
    f.seek(part + 0x10000)
    hdr = f.read(0x800)
    assert hdr[:20] == b'MICROSOFT*XBOX*MEDIA'
    root, size = struct.unpack_from('<II', hdr, 20)
    dirs, files = [], {}

    def walk(sec, size, path):
        f.seek(part + sec * 2048)
        d = f.read((size + 2047) // 2048 * 2048)
        dirs.append((sec, size, path, d))

        def node(o):
            if o * 4 + 14 > size:
                return
            l, r, s, sz, attr, nl = struct.unpack_from('<HHIIBB', d, o * 4)
            if l == 0xFFFF:
                return
            n = d[o * 4 + 14:o * 4 + 14 + nl].decode('latin1')
            if attr & 0x10:
                if sz:
                    walk(s, sz, path + n + '/')
            else:
                files[path + n] = (s, sz)
            if l:
                node(l)
            if r:
                node(r)
        node(0)
    walk(root, size, '/')
    return hdr, dirs, files


def c_bytes(b, indent='    '):
    out = []
    for i in range(0, len(b), 24):
        out.append(indent + ''.join('0x%02X,' % x for x in b[i:i + 24]))
    return '\n'.join(out)


def main():
    base_path, redump_path, out_path = sys.argv[1:4]
    base, red = open(base_path, 'rb'), open(redump_path, 'rb')
    base.seek(0, 2)
    total = base.tell()
    base.seek(0)
    pre = base.read(0x10000)
    hdr, dirs, files = tree(base, 0)
    _, _, rfiles = tree(red, REDUMP_PART)

    # the banner: its non-zero runs
    runs, i = [], 0
    while i < len(pre):
        if pre[i]:
            j = i
            while j < len(pre) and (pre[j] or any(pre[j:j + 16])):
                j += 1
            runs.append((i, pre[i:j]))
            i = j
        else:
            i += 1

    fixes = []
    for p in ('/default.xbe', '/NinjaTomoe.xbe', '/NinjaTrilogy.xbe'):
        s, z = files[p]
        base.seek(s * 2048)
        x = base.read(0x1000)
        rs, rz = rfiles[p]
        red.seek(REDUMP_PART + rs * 2048)
        y = red.read(0x1000)
        assert z == rz
        fixes += [(p, k, x[k]) for k in range(len(x)) if x[k] != y[k]]

    o = ['// Generated by tools/gen_ngb_base_layout.py: the Hurricane patches\' base image as made from the Redump disc',
         '// (layout only: the volume header, extract-xiso\'s banner, directory tables, certificate bytes). Do not edit.',
         '#pragma once', '',
         'constexpr uint64_t kBaseSize = %du;' % total,
         'constexpr uint32_t kRedumpPartition = 0x%Xu;' % REDUMP_PART, '',
         'const uint8_t kBaseHeader[2048] = {', c_bytes(hdr), '};', '']
    for n, (off, b) in enumerate(runs):
        o += ['const uint8_t kBanner%d[%d] = {' % (n, len(b)), c_bytes(b), '};']
    o += ['const struct { uint32_t offset, size; const uint8_t *bytes; } kBanner[] = {']
    o += ['    {0x%X, %d, kBanner%d},' % (off, len(b), n) for n, (off, b) in enumerate(runs)] + ['};', '']
    for n, (sec, size, path, d) in enumerate(dirs):
        o += ['const uint8_t kDir%d[%d] = { // %s' % (n, len(d), path), c_bytes(d), '};']
    o += ['const struct { uint32_t sector, size; const char *path; const uint8_t *table; } kDirs[] = {']
    o += ['    {0x%X, %d, "%s", kDir%d},' % (sec, size, path, n) for n, (sec, size, path, d) in enumerate(dirs)] + ['};', '']
    o += ['const struct { const char *path; uint32_t offset; uint8_t value; } kFixes[] = {']
    o += ['    {"%s", 0x%X, 0x%02X},' % f for f in fixes] + ['};', '']
    open(out_path, 'w', newline='\n').write('\n'.join(o))
    print('%d banner runs, %d directories, %d fixes, %d bytes' % (len(runs), len(dirs), len(fixes), total))


if __name__ == '__main__':
    main()
