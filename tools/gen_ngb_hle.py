#!/usr/bin/env python3
"""Generate the Ninja Gaiden Black x2.1 HLE tables from BLACK's.

The D3D8LTCG and DSOUND libraries are the same XDK 5849 builds in both games, so every HLE implementation written for
BLACK applies to the same-named function in x2.1; only the entry address and the LTCG register convention can differ.
For each H()/HN() entry of BLACK's tables in loader/src/{d3d/device,d3d/draw,d3d/resources,audio/dsound}.cpp this
script looks the function up by name in XbSymbolDatabase's x2.1 output (names carry the convention, e.g.
D3DDevice_SetTexture_4__LTCG_eax1 = stage in eax, texture on the stack) and writes
loader/src/ngb/<file>_table.inc with the x2.1 address and parameter sources. Output holds addresses, names and
conventions only, no game code.

Usage: python -I tools/gen_ngb_hle.py <symbols_x21.json> <lib_calls_x21.txt> loader/src
"""
import json
import os
import re
import sys

FILES = {'d3d/device.cpp': 'device', 'd3d/draw.cpp': 'draw', 'd3d/resources.cpp': 'resources', 'audio/dsound.cpp': 'dsound'}
ENTRY = re.compile(r'^\s*(H|HN)\((0x[0-9a-fA-F]+),\s*(?:"([^"]+)",\s*)?(\w+),\s*"([^"]*)",\s*(true|false)\)')


def base_name(n):
    n = re.sub(r'__LTCG.*$', '', n)
    n = re.sub(r'_\d+$', '', n)
    return n


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    syms_path, calls_path, src = sys.argv[1:]
    syms = [s for s in json.load(open(syms_path, encoding='utf-8')) if s['kind'] == 'FUN']
    by_base = {}
    for s in syms:
        by_base.setdefault(base_name(s['name']), s)
    # D3D / DSOUND targets the game calls (tools/xbe_census.py report), for the "still missing" list
    called = {}
    sec = None
    for line in open(calls_path, encoding='utf-8'):
        m = re.match(r'^== (\w+):', line)
        if m:
            sec = m.group(1)
            continue
        m = re.match(r'^\s+(0x[0-9a-f]+)\s+(\d+)\s+(\S+)', line)
        if m and sec in ('D3D', 'DSOUND') and int(m.group(2)) > 0:
            called[m.group(1)] = (sec, m.group(3), int(m.group(2)))

    covered = set()
    missing_syms = []
    for rel, short in FILES.items():
        lines = open(os.path.join(src, rel), encoding='utf-8').read().splitlines()
        out = []
        for line in lines:
            m = ENTRY.match(line)
            if not m:
                continue
            kind, addr, api, impl, params, ret = m.groups()
            api = api or impl
            s = by_base.get(base_name(api))
            if not s:
                missing_syms.append((short, api))
                continue
            # psh = one stack dword, psh2 = a 64-bit stack value (two dwords for the thunk), else a register
            p = ' '.join('s' if q['where'] == 'psh' else 's s' if q['where'] == 'psh2' else q['where'] for q in s['params'])
            if len(p.split()) != len(params.split()):
                # LTCG dropped or added parameters: BLACK's implementation cannot take the call as is (ngb/d3d_ngb.cpp wraps it)
                print('  needs a wrapper (parameter count %d, BLACK %d): %s at 0x%08x' % (len(p.split()), len(params.split()), s['name'], s['addr']))
                continue
            out.append('{0x%08xu, "%s", (void *)&%s, "%s", %s}, // BLACK %s "%s"' % (s['addr'], s['name'], impl, p, ret, addr, params))
            covered.add('0x%08x' % s['addr'])
        dst = os.path.join(src, 'ngb', short + '_table.inc')
        with open(dst, 'w', newline='\n') as f:
            f.write('// Generated by tools/gen_ngb_hle.py from the BLACK table in %s and XbSymbolDatabase for x2.1. Do not edit.\n' % rel)
            f.write('// {address, name, implementation, parameter sources, returns a value}\n')
            f.write('\n'.join(out) + '\n')
        print('%s: %d entries' % (dst, len(out)))
    print('\nBLACK entries without an x2.1 symbol (%d):' % len(missing_syms))
    for short, api in missing_syms:
        print('  %-10s %s' % (short, api))
    todo = [(a, v) for a, v in called.items() if a not in covered]
    todo.sort(key=lambda e: -e[1][2])
    print('\nx2.1 D3D/DSOUND targets called from .text with no HLE entry (%d):' % len(todo))
    for a, (sec, name, n) in todo:
        print('  %-7s %s %4d %s' % (sec, a, n, name))


if __name__ == '__main__':
    main()
